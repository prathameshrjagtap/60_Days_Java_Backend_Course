package Static_Variables;

public class Static_Division 
{
	static int divNum1 = 9;
	static int divNum2 = 3;
	static int div = divNum1 / divNum2; // doing Division operation
	
	public static void main(String args[])
	{
		System.out.println("Division of two Static Variable values is : " + div); // div will be used to print the result
		
	}
}
