package Static_Variables;

public class Static_Addition 
{
	static int addnum1 = 5;
	static int addnum2 = 4;
	static int sum = addnum1 + addnum2; //doing Addition operation
	
	public static void main(String args[])
	{
		
		System.out.println("Addition of two Static Variable values is : " + sum); //We can use the static sum variable for printing the output
		
	}
}
