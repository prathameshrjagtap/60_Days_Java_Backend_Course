package Static_Variables;

public class Static_Multiplication 
{
	static int mulNum1 = 7;
	static int mulNum2 = 4;
	static int mul = mulNum1 * mulNum2; // doing multiplication operation
	
	public static void main(String args[]) 
	{
		System.out.println("Multiplication of two Static Variable values is : " + mul); // mul will be used to display the result
		
	}
}
