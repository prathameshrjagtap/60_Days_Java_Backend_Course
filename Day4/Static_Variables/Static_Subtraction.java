package Static_Variables;

public class Static_Subtraction 
{
	static int subnum1 = 9;
	static int subnum2 = 6;
	static int sub = subnum1 - subnum2; // doing subtraction operation
	
	public static void main(String args[])
	{
		System.out.println("Subtraction of two Static Varibles value is : " + sub); // Static Variable sub will be used to print the output value
		
	}

}
