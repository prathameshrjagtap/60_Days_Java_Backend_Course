package Day7;

public class Relational_Operators {
	public static void main(String args[]) {
		//Relation Operator: <, >, <=, >=, ==, !=
		int a = 5;
		int b = 3;
		
		System.out.println(a>b); //5>3 = true 
		System.out.println(a<b); //5<3 = false
		System.out.println(a<=b);//5<=3 = false
		System.out.println(a>=b);//5>=3 = true
		System.out.println(a==b);//5==3 = false
		System.out.println(a!=b);//5!=3 = true
	}
}
